// Generates the Sabal palm mark geometry once, and writes:
//   src/components/logoGeometry.js  (paths used by the React <Logo/> component)
//   public/logo-light.svg, public/logo-dark.svg, public/favicon.svg
import { writeFileSync, mkdirSync } from 'node:fs'

const r2 = (n) => Math.round(n * 100) / 100
const P = (x, y) => `${r2(x)} ${r2(y)}`

// ---- Mark geometry (viewBox 0 0 200 240) ----
const apex = { x: 100, y: 112 }

// Each frond: direction (deg, 0 = up, clockwise), distance from apex to frond heart, spine length, spread
const fronds = [
  { dir: 0,    dist: 34, len: 54, spread: 175, n: 33 },
  { dir: -50,  dist: 34, len: 50, spread: 170, n: 31 },
  { dir: 50,   dist: 34, len: 50, spread: 170, n: 31 },
  { dir: -96,  dist: 40, len: 46, spread: 165, n: 29 },
  { dir: 96,   dist: 40, len: 46, spread: 165, n: 29 },
]
const rad = (d) => ((d - 90) * Math.PI) / 180

let petioles = ''
let spines = ''
for (const f of fronds) {
  const hx = apex.x + Math.cos(rad(f.dir)) * f.dist
  const hy = apex.y + Math.sin(rad(f.dir)) * f.dist
  // petiole from apex to heart, slight curve
  const cx = apex.x + Math.cos(rad(f.dir)) * f.dist * 0.5 + (f.dir === 0 ? 0 : Math.sign(f.dir) * 3)
  const cy = apex.y + Math.sin(rad(f.dir)) * f.dist * 0.5 + 4
  petioles += `M${P(apex.x, apex.y)} Q${P(cx, cy)} ${P(hx, hy)} `
  for (let i = 0; i < f.n; i++) {
    const t = i / (f.n - 1)
    const a = f.dir - f.spread / 2 + t * f.spread
    // longer spines in the middle of the fan, shorter at the edges
    const edge = Math.abs(t - 0.5) * 2
    const L = f.len * (1 - 0.35 * edge * edge)
    const ex = hx + Math.cos(rad(a)) * L
    const ey = hy + Math.sin(rad(a)) * L
    // gentle droop: bend the spine end slightly downward
    const mx = hx + Math.cos(rad(a)) * L * 0.55
    const my = hy + Math.sin(rad(a)) * L * 0.55 - 1.5
    spines += `M${P(hx, hy)} Q${P(mx, my)} ${P(ex, ey + 2.5)} `
  }
}

// Trunk: tapered polygon with crosshatch
const trunkTop = 110, trunkBase = 206
const wTop = 7.5, wBase = 12
const trunk = `M${P(100 - wTop, trunkTop)} L${P(100 + wTop, trunkTop)} L${P(100 + wBase, trunkBase)} L${P(100 - wBase, trunkBase)} Z`
let hatch = ''
for (let y = trunkTop + 8; y < trunkBase - 4; y += 9) {
  const w = wTop + ((y - trunkTop) / (trunkBase - trunkTop)) * (wBase - wTop)
  hatch += `M${P(100 - w, y)} L${P(100 + w, y + 7)} M${P(100 + w, y)} L${P(100 - w, y + 7)} `
}

// Roots
const roots = [
  [100, 206, 92, 222, 70, 230, 48, 232],
  [100, 206, 108, 222, 130, 230, 152, 232],
  [100, 206, 96, 220, 86, 232, 74, 238],
  [100, 206, 104, 220, 114, 232, 126, 238],
  [100, 206, 100, 222, 100, 232, 100, 239],
  [100, 206, 90, 216, 62, 220, 36, 218],
  [100, 206, 110, 216, 138, 220, 164, 218],
]
let rootPath = ''
for (const r of roots) rootPath += `M${P(r[0], r[1])} C${P(r[2], r[3])} ${P(r[4], r[5])} ${P(r[6], r[7])} `
const ground = `M${P(28, 212)} L${P(84, 212)} M${P(116, 212)} L${P(172, 212)}`

const geometry = { petioles: petioles.trim(), spines: spines.trim(), trunk, hatch: hatch.trim(), roots: rootPath.trim(), ground }

mkdirSync('src/components', { recursive: true })
writeFileSync(
  'src/components/logoGeometry.js',
  `// Generated by scripts/gen-logo.mjs. Do not edit by hand.\nexport const MARK_VIEWBOX = '0 0 200 240'\nexport const MARK = ${JSON.stringify(geometry, null, 2)}\n`,
)

// ---- Standalone SVG files ----
const markGroup = (goldId) => `
  <g fill="none" stroke="url(#${goldId})" stroke-linecap="round" stroke-linejoin="round">
    <path d="${geometry.spines}" stroke-width="1.5"/>
    <path d="${geometry.petioles}" stroke-width="2.2"/>
    <path d="${geometry.roots}" stroke-width="2.6"/>
    <path d="${geometry.ground}" stroke-width="1.6"/>
  </g>
  <path d="${geometry.trunk}" fill="url(#${goldId})"/>
  <path d="${geometry.hatch}" fill="none" stroke="#3A2A0E" stroke-opacity=".45" stroke-width="1"/>`

const gold = (id) => `<linearGradient id="${id}" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#D9B86A"/><stop offset=".55" stop-color="#BF9449"/><stop offset="1" stop-color="#9A7230"/>
    </linearGradient>`

const lockup = ({ bg, word, sub, rule, file }) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 760 240" width="760" height="240" role="img" aria-label="Sabal Tax &amp; Estate Law, LLP">
  <title>Sabal Tax &amp; Estate Law, LLP</title>
  <defs>${gold('g')}</defs>
  ${bg ? `<rect width="760" height="240" fill="${bg}"/>` : ''}
  <g transform="translate(20 0)">${markGroup('g')}</g>
  <text x="250" y="138" font-family="'Cormorant Garamond','Cormorant',Garamond,'Times New Roman',serif" font-weight="600" font-size="118" fill="${word}">Sabal</text>
  <rect x="252" y="156" width="470" height="2" fill="${rule}"/>
  <text x="254" y="196" font-family="'Cormorant Garamond','Cormorant',Garamond,'Times New Roman',serif" font-weight="500" font-size="31" letter-spacing="5" fill="${sub}">TAX &amp; ESTATE LAW, LLP</text>
</svg>
`
mkdirSync('public', { recursive: true })
writeFileSync('public/logo-dark.svg', lockup({ bg: '#0B1A33', word: '#F7F2E8', sub: '#F7F2E8', rule: '#BF9449' }))
writeFileSync('public/logo-light.svg', lockup({ bg: '', word: '#0B1A33', sub: '#0B1A33', rule: '#A97E2E' }))

const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 240 240" width="240" height="240">
  <defs>${gold('g')}</defs>
  <rect width="240" height="240" rx="48" fill="#0B1A33"/>
  <g transform="translate(26 8) scale(0.94)">${markGroup('g')}</g>
</svg>
`
writeFileSync('public/favicon.svg', favicon)
console.log('logo files written')
